#!/usr/bin/env bash
# Builds the JAR, runs it, executes every required test scenario with curl, restarts the app to
# show persistence, runs an H2 query, and writes all evidence to REPORT.md + evidence/.
# Works on Linux, macOS and Git Bash on Windows. Needs: JDK 17+, Maven 3.9+, curl.
#
#   ./demo.sh              fresh run (deletes ./data and ./logs first so the evidence is clean)
#   ./demo.sh --keep-data  keep the existing H2 file
set -uo pipefail

cd "$(dirname "$0")"
BASE="http://localhost:8080"
EVID="evidence"
REPORT="REPORT.md"
JAR=""
APP_PID=""

if [[ "${1:-}" != "--keep-data" ]]; then rm -rf data logs; fi
rm -rf "$EVID"; mkdir -p "$EVID"

pretty() { # pretty-print JSON if python is available, else raw
  local py; py=$(command -v python3 || command -v python || true)
  if [[ -n "$py" ]] && "$py" -c "import json,sys; print(json.dumps(json.load(sys.stdin), indent=2))" 2>/dev/null <<<"$1"; then :; else printf '%s\n' "$1"; fi
}

md() { printf '%s\n' "$@" >> "$REPORT"; }

# call TITLE METHOD PATH [JSON_BODY]  -> appends request/status/response to the report, sets LAST_BODY/LAST_STATUS
call() {
  local title="$1" method="$2" path="$3" body="${4:-}" out
  if [[ -n "$body" ]]; then
    out=$(curl -s -X "$method" "$BASE$path" -H "Content-Type: application/json" -d "$body" -w $'\n%{http_code}')
  else
    out=$(curl -s -X "$method" "$BASE$path" -w $'\n%{http_code}')
  fi
  LAST_STATUS="${out##*$'\n'}"
  LAST_BODY="${out%$'\n'*}"
  md "### $title" "" '```http' "$method $path"
  [[ -n "$body" ]] && md "Content-Type: application/json" "" "$body"
  md '```' "" "**Status:** \`$LAST_STATUS\`" ""
  if [[ -n "$LAST_BODY" ]]; then md '```json'; pretty "$LAST_BODY" >> "$REPORT"; md '```'; else md "_(empty body)_"; fi
  md ""
  printf '  %-55s %s\n' "$title" "$LAST_STATUS"
}

expect() { # expect STATUS
  if [[ "$LAST_STATUS" != "$1" ]]; then echo "  !! expected $1, got $LAST_STATUS"; FAILURES=$((FAILURES+1)); fi
}

start_app() { # start_app LOGFILE
  java -jar "$JAR" > "$1" 2>&1 &
  APP_PID=$!
  for _ in $(seq 1 90); do
    if curl -s -o /dev/null "$BASE/students"; then return 0; fi
    sleep 1
  done
  echo "App did not start in 90 s. See $1"; exit 1
}

stop_app() {
  if [[ -f "/proc/$APP_PID/winpid" ]]; then           # Git Bash on Windows
    taskkill //PID "$(cat /proc/$APP_PID/winpid)" //F > /dev/null 2>&1
  else
    kill "$APP_PID" 2>/dev/null
  fi
  wait "$APP_PID" 2>/dev/null
  for _ in $(seq 1 20); do curl -s -o /dev/null "$BASE/students" || break; sleep 1; done
}

id_of() { sed -n 's/.*"id":\([0-9]*\).*/\1/p' <<<"$1" | head -1; }

FAILURES=0

echo "==> Building"
mvn -q -B clean package -DskipTests || { echo "Build failed"; exit 1; }
JAR=$(ls target/student-api-*.jar | grep -v '\.original$' | head -1)
H2_JAR=$(ls "$HOME"/.m2/repository/com/h2database/h2/*/h2-*.jar 2>/dev/null | grep -v sources | tail -1)

JAVA_VER=$(java -version 2>&1 | head -1)
MVN_VER=$(mvn -v 2>/dev/null | head -1)
BOOT_VER=$(sed -n '/spring-boot-starter-parent/{n;s/.*<version>\(.*\)<\/version>.*/\1/p;}' pom.xml)

: > "$REPORT"
md "# Student Record Management API: Test Report" ""
md "Generated by \`demo.sh\` on $(date '+%Y-%m-%d %H:%M:%S %Z'). Every request, status code and response body below was captured live from the running JAR." ""
md "| Item | Value |" "|---|---|"
md "| Java | \`$JAVA_VER\` |" "| Build tool | \`$MVN_VER\` |" "| Spring Boot | \`$BOOT_VER\` |"
md "| Artifact | \`$JAR\` |" "| H2 mode | **File-based**: \`jdbc:h2:file:./data/studentdb\` (stored in \`data/studentdb.mv.db\`) |" ""

echo "==> Run 1: starting $JAR"
start_app "$EVID/run1-console.log"

md "## 1. Startup log (run 1)" "" "Command: \`java -jar $JAR\`" "" '```text'
grep -E "Starting StudentApiApplication|Tomcat started|Started StudentApiApplication|DataSeeder|Student API ready" "$EVID/run1-console.log" >> "$REPORT"
md '```' ""

md "## 2. Create → retrieve → update → delete, with error cases" ""
echo "==> Scenarios"
call "2.1 List all students (3 seeded records)" GET "/students"; expect 200

call "2.2 Valid creation" POST "/students" '{"usn":"1JS23CS101","name":"Mahantesh R. Patted","department":"CSE","semester":5}'; expect 201
NEW_ID=$(id_of "$LAST_BODY")

call "2.3 Retrieve the created student" GET "/students/$NEW_ID"; expect 200

call "2.4 Duplicate USN on create (case-insensitive: lower-case USN still collides)" POST "/students" '{"usn":"1js23cs101","name":"Someone Else","department":"ISE","semester":3}'; expect 409

call "2.5 Invalid semester (9)" POST "/students" '{"usn":"1JS23CS102","name":"Test User","department":"CSE","semester":9}'; expect 400

call "2.6 Blank USN, blank name and semester 0" POST "/students" '{"usn":"  ","name":"","department":"CSE","semester":0}'; expect 400

call "2.7 Department filtering (?department=CSE)" GET "/students?department=CSE"; expect 200

call "2.8 Update (PUT) the created student" PUT "/students/$NEW_ID" '{"usn":"1JS23CS101","name":"Mahantesh R. Patted","department":"AIML","semester":6}'; expect 200

call "2.9 Update with a USN owned by another student" PUT "/students/$NEW_ID" '{"usn":"1JS23CS001","name":"Mahantesh R. Patted","department":"AIML","semester":6}'; expect 409

call "2.10 PUT on a missing id does not create it" PUT "/students/99999" '{"usn":"1JS23CS999","name":"Ghost","department":"CSE","semester":1}'; expect 404

call "2.11 Retrieve after failed update attempts (data unchanged by 2.9 and 2.10)" GET "/students/$NEW_ID"; expect 200

call "2.12 Delete the created student" DELETE "/students/$NEW_ID"; expect 204

call "2.13 Lookup after deletion" GET "/students/$NEW_ID"; expect 404

call "2.14 Non-numeric id" GET "/students/abc"; expect 400

call "2.15 Final list: only seeds remain, no invalid request changed data" GET "/students"; expect 200

md "## 3. H2 query result" ""
if [[ -n "$H2_JAR" ]]; then
  SQL="SELECT ID, USN, NAME, DEPARTMENT, SEMESTER FROM STUDENTS ORDER BY ID"
  md "Run with the H2 Shell against the same database file while the app is running (\`AUTO_SERVER=TRUE\` allows a second connection):" ""
  md '```text' "java -cp $(basename "$H2_JAR") org.h2.tools.Shell -url \"jdbc:h2:file:./data/studentdb;AUTO_SERVER=TRUE\" -user sa -sql \"$SQL\""
  md "" "$(java -cp "$H2_JAR" org.h2.tools.Shell -url "jdbc:h2:file:./data/studentdb;AUTO_SERVER=TRUE" -user sa -password "" -sql "$SQL" 2>&1 | grep -v JAVA_TOOL_OPTIONS)" '```' ""
else
  md "_H2 jar not found in ~/.m2; use the H2 console instead (see README)._" ""
fi

md "## 4. Restart observation" ""
call "4.1 Create a marker record before restarting" POST "/students" '{"usn":"1JS23CS555","name":"Restart Marker","department":"ISE","semester":2}'; expect 201
MARKER_ID=$(id_of "$LAST_BODY")
BEFORE=$(curl -s "$BASE/students")

echo "==> Stopping and restarting"
stop_app
start_app "$EVID/run2-console.log"

md "Stopped the JAR and started it again with the same command. Startup log of run 2:" "" '```text'
grep -E "Started StudentApiApplication|DataSeeder|Student API ready" "$EVID/run2-console.log" >> "$REPORT"
md '```' ""
call "4.2 Marker record after restart" GET "/students/$MARKER_ID"; expect 200
call "4.3 Full list after restart" GET "/students"; expect 200
AFTER="$LAST_BODY"

md "**Observation:** H2 is file-based, so all records survive the restart, including the marker created at runtime (id $MARKER_ID). The seeder found its three USNs already present, so it logged \`inserted=0, skipped(already present)=3\` and created no duplicates."
if [[ "$BEFORE" == "$AFTER" ]]; then md "The list before and after the restart is identical." ""; else md "**Warning:** the list differed before and after restart." ""; FAILURES=$((FAILURES+1)); fi
md "With an in-memory URL (\`jdbc:h2:mem:studentdb\`) the database would be dropped when the JVM exits: only the three seeds would come back, with new ids, and the marker would be gone." ""

call "4.4 Cleanup: delete marker" DELETE "/students/$MARKER_ID"; expect 204

md "## 5. Logging sample" "" "From \`logs/student-api.log\`: successful mutations at INFO and failed requests at WARN, each with timestamp, level, thread and class name. No full student records are logged." "" '```text'
grep -E "StudentService|GlobalExceptionHandler|DataSeeder" logs/student-api.log | head -25 >> "$REPORT"
md '```' ""

md "## 6. Why the service layer is separate from the controller" ""
md "The controller only handles HTTP: it maps URLs, reads JSON, triggers bean validation and picks status codes. The service owns the business rules: USN normalisation and uniqueness, \"PUT never creates\", transactions and mutation logging. Keeping them apart means the same rules apply whether a request comes from REST, the startup seeder or a future batch job, and each layer can be tested on its own (the service with a mocked repository, the controller with a mocked service). It also lets the transport change, for example to GraphQL or messaging, without touching the logic that protects the data." ""

stop_app

md "---" "" "Result: **$FAILURES unexpected status code(s)**. Full console output: \`evidence/run1-console.log\`, \`evidence/run2-console.log\`."
echo
if [[ $FAILURES -eq 0 ]]; then echo "All scenarios returned the expected status codes. Report: $REPORT"; else echo "$FAILURES scenario(s) returned unexpected codes. See $REPORT"; fi
